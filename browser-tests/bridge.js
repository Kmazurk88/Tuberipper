const { chromium } = require('playwright');
const sleep = ms => new Promise(r => setTimeout(r, ms));
let failures = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) failures++; };
(async () => {
  const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const page = await (await browser.newContext({ viewport: { width: 412, height: 915 }, hasTouch: true, isMobile: true })).newPage();
  await require('./bm.js')(page);
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.addInitScript(() => { window.__calls = []; window.TRNative = { update: j => window.__calls.push(['update', JSON.parse(j)]), clear: () => window.__calls.push(['clear']) }; });
  await page.goto('http://tr-test:8000/'); await page.waitForSelector('.recents-grid');
  ok((await page.evaluate(() => window.__calls.filter(c => c[0] === 'update' && c[1].playing).length)) === 0, 'nothing is reported as playing at startup');
  await page.locator('.tabbtn[data-tab=library]').click();
  await page.locator('#tab-library .chip', { hasText: 'Podcasts' }).click();
  await page.locator('#tab-library .row', { hasText: 'Conan' }).first().click();
  await page.waitForSelector('#tab-library .page:last-child .ep');
  await page.locator('#tab-library .page:last-child .ep').last().locator('.ep-play').click();
  await sleep(3500);
  const last = () => page.evaluate(() => window.__calls.filter(c => c[0] === 'update').pop()[1]);
  let u = await last();
  ok(u.playing && u.title && u.artist && u.art.startsWith('http://tr-test:8000/api/nd/cover/') && u.dur > 60000, 'page reports playing: "' + u.title.slice(0, 40) + '…" dur=' + Math.round(u.dur / 60000) + 'min, absolute cover URL');
  await page.evaluate(() => window.TRNative_cmd('pause')); await sleep(600);
  u = await last(); ok(!u.playing, 'notification "pause" pauses and is reported');
  const posPaused = u.pos;
  await page.evaluate(() => window.TRNative_cmd('play')); await sleep(1500);
  u = await last(); ok(u.playing, 'notification "play" resumes');
  await page.evaluate(() => window.TRNative_cmd('seek:600000')); await sleep(1500);
  u = await last(); ok(u.pos >= 600000 && u.pos < 640000, 'lock-screen seek jumps to 10:00 (pos=' + Math.round(u.pos / 1000) + 's)');
  await page.evaluate(() => window.TRNative_cmd('ffwd')); await sleep(1200);
  const after = await last(); ok(after.pos >= u.pos + 29000, 'fast-forward skips +30s');
  await page.evaluate(() => window.TRNative_cmd('rew')); await sleep(1200);
  const back = await last(); ok(back.pos <= after.pos - 10000, 'rewind goes back 15s');
  const t1 = (await last()).title;
  await page.evaluate(() => window.TRNative_cmd('next')); await sleep(3000);
  u = await last(); ok(u.title !== t1 && u.playing, 'notification "next" plays the next episode');
  await page.evaluate(() => window.TRNative_cmd('pause')); await sleep(800);
  // cleanup the bookmarks this made
  await page.evaluate(async () => { const b = (await (await fetch('api/nd/rest/getBookmarks')).json())['subsonic-response'].bookmarks.bookmark || []; for (const x of b) await fetch('api/nd/rest/deleteBookmark?id=' + x.entry.id); });
  console.log('errors:', errs); console.log(failures ? failures + ' FAILED' : 'ALL PASSED');
  await browser.close(); process.exit(failures ? 1 : 0);
})().catch(e => { console.error('CRASH', e.message.split('\n').slice(0, 5).join('\n')); process.exit(2); });
